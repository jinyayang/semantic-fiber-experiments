# ===================== 3. 提取 Router Logits =====================
def extract_router_logits(model, tokenizer, texts, max_length=512):
    # transformers 4.40.0 不支持 output_router_logits，直接走 hook
    return extract_with_hook(model, tokenizer, texts, max_length)

def extract_with_hook(model, tokenizer, texts, max_length):
    """Fallback：用 hook 抓 gate 概率（如果官方接口不可用）。"""
    probs_list = []
    hooks = []
    
    def make_hook():
        def hook(module, input, output):
            if hasattr(module, 'gate'):
                hidden = input[0]
                logits = module.gate(hidden)
                probs = torch.softmax(logits, dim=-1)
                probs_list.append(probs.detach().cpu())
        return hook
    
    # 注册 hook 到每一层的 mlp
    for layer in model.model.layers:
        if hasattr(layer, 'mlp') and hasattr(layer.mlp, 'gate'):
            hooks.append(layer.mlp.register_forward_hook(make_hook()))
    
    combined = "\n".join(texts)
    inputs = tokenizer(combined, return_tensors="pt", truncation=True, max_length=max_length).to(device)
    
    with torch.no_grad():
        model(**inputs)
    
    for h in hooks:
        h.remove()
    
    if not probs_list:
        raise RuntimeError("No gate probs captured. Model architecture may differ.")
    
    # 堆叠：[num_layers, batch, seq_len, num_experts]
    return torch.stack([p for p in probs_list])

# ===================== 4. 方向 A：多阈值敏感性分析 =====================
def direction_a(texts, thresholds=[0.1, 0.3, 0.5, 0.7, 0.9]):
    print("\n=== Direction A: Threshold Sensitivity ===")
    probs = extract_router_logits(model, tokenizer, texts)  # [L, B, T, E]
    
    # 取所有层、所有 token 的概率：[L*T, E]
    L, B, T, E = probs.shape
    flat_probs = probs.view(L * B * T, E)
    
    # 排序
    sorted_p, _ = torch.sort(flat_probs, descending=True, dim=-1)
    top1 = sorted_p[:, 0]
    top2 = sorted_p[:, 1]
    ratio = top2 / (top1 + 1e-8)
    
    results = {}
    for th in thresholds:
        overlap = (ratio > th).sum().item()
        total = ratio.numel()
        pct = overlap / total * 100
        results[th] = pct
        print(f"  Threshold {th:.1f}: overlap = {overlap}/{total} ({pct:.2f}%)")
    
    return results

# ===================== 5. 方向 B：语义一致性（Math vs Law vs Neutral） =====================
def direction_b(texts_dict):
    print("\n=== Direction B: Semantic Consistency ===")
    distributions = {}
    
    for label, texts in texts_dict.items():
        probs = extract_router_logits(model, tokenizer, texts)  # [L, B, T, E]
        L, B, T, E = probs.shape
        
        # 取所有 token 的 top-1 专家
        top1_experts = torch.argmax(probs, dim=-1)  # [L, B, T]
        flat_top1 = top1_experts.view(-1)
        
        # 统计每个专家的比例
        counts = torch.bincount(flat_top1, minlength=E).float()
        proportions = (counts / counts.sum() * 100).tolist()
        
        print(f"  {label} (tokens={flat_top1.numel()}, experts={E}): " + 
              ", ".join([f"E{i}={proportions[i]:.1f}%" for i in range(E)]))
        distributions[label] = proportions
    
    # 计算两两欧氏距离
    labels = list(distributions.keys())
    for i in range(len(labels)):
        for j in range(i+1, len(labels)):
            d = sum((distributions[labels[i]][k] - distributions[labels[j]][k])**2 
                    for k in range(len(distributions[labels[i]]))) ** 0.5
            print(f"  {labels[i]} <-> {labels[j]}: {d:.2f}")
    
    return distributions

